// Одноразовый генератор maps/*.json. Пишет обычные JSON-карты —
// игра читает только JSON, этот скрипт ей не нужен (задел под редактор).
// Запуск: node tools/gen_maps.mjs
import { writeFileSync, mkdirSync } from 'node:fs';

function makeMap(id, name, palette) {
  const blocks = new Map(); // "x|y|z" -> type
  const put = (x, y, z, t) => blocks.set(`${x}|${y}|${z}`, t);
  const fill = (x0, y0, z0, x1, y1, z1, t) => {
    for (let x = x0; x <= x1; x++)
      for (let y = y0; y <= y1; y++)
        for (let z = z0; z <= z1; z++) put(x, y, z, t);
  };
  const clear = (x0, y0, z0, x1, y1, z1) => {
    for (let x = x0; x <= x1; x++)
      for (let y = y0; y <= y1; y++)
        for (let z = z0; z <= z1; z++) blocks.delete(`${x}|${y}|${z}`);
  };
  return {
    put, fill, clear,
    save(spawns, weapons) {
      const arr = [...blocks.entries()].map(([k, t]) => {
        const [x, y, z] = k.split('|').map(Number);
        return [x, y, z, t];
      });
      const json = { id, name, palette, blocks: arr, spawns, weapons };
      writeFileSync(new URL(`../maps/${id}.json`, import.meta.url), JSON.stringify(json));
      console.log(`${id}: ${arr.length} blocks`);
    },
  };
}

mkdirSync(new URL('../maps/', import.meta.url), { recursive: true });

// ---------- ARENA 01: тесная арена 24×24, укрытия, ближний бой ----------
{
  const P = { 1: '#6fbf4a', 2: '#8d939c', 3: '#c9812f', 4: '#3fc9d6', 5: '#57606b', 6: '#e0e4e8' };
  const m = makeMap('arena01', 'arena01', P);
  const S = 24;
  // пол: трава с каменной рамкой
  m.fill(0, 0, 0, S - 1, 0, S - 1, 1);
  m.fill(0, 0, 0, S - 1, 0, 1, 5); m.fill(0, 0, S - 2, S - 1, 0, S - 1, 5);
  m.fill(0, 0, 0, 1, 0, S - 1, 5); m.fill(S - 2, 0, 0, S - 1, 0, S - 1, 5);
  // периметр, высота 3
  m.fill(0, 1, 0, S - 1, 3, 0, 2); m.fill(0, 1, S - 1, S - 1, 3, S - 1, 2);
  m.fill(0, 1, 0, 0, 3, S - 1, 2); m.fill(S - 1, 1, 0, S - 1, 3, S - 1, 2);
  // укрытия — симметрия на 180° вокруг центра (12,12): fair play
  const sym = (x0, z0, x1, z1, y0, y1, t) => {
    m.fill(x0, y0, z0, x1, y1, z1, t);
    m.fill(S - 1 - x1, y0, S - 1 - z1, S - 1 - x0, y1, S - 1 - z0, t);
  };
  // центральный блок с "короной" — вокруг него лежит дробовик
  m.fill(11, 1, 11, 12, 2, 12, 6);
  // L-стенки в четвертях
  sym(6, 6, 9, 6, 1, 2, 3);   // горизонтальная часть L
  sym(6, 7, 6, 9, 1, 2, 3);   // вертикальная часть L
  // одиночные колонны высотой 3 — прятаться в полный рост
  sym(16, 6, 17, 7, 1, 3, 2);
  // низкие ящики для перепрыгивания
  sym(11, 4, 12, 5, 1, 1, 3);
  sym(4, 11, 5, 12, 1, 1, 3);
  // акцентные плиты у спавнов
  m.fill(2, 0, 2, 4, 0, 4, 4); m.fill(S - 5, 0, S - 5, S - 3, 0, S - 3, 4);
  m.save(
    [[3.5, 1, 3.5, 225], [20.5, 1, 20.5, 45]],
    [
      { type: 1, pos: [12, 3.6, 12] },        // дробовик на центральном блоке
      { type: 2, pos: [20.5, 1.6, 3.5] },     // рейлган — нейтральный угол
      { type: 1, pos: [3.5, 1.6, 20.5] },     // второй дробовик — другой угол
    ],
  );
}

// ---------- ARENA 02: двухуровневая с рампами, 28×28 ----------
{
  const P = { 1: '#d8b56a', 2: '#7a828c', 3: '#b05548', 4: '#3fc9d6', 5: '#4d5560', 6: '#e0e4e8', 7: '#9c6b3f' };
  const m = makeMap('arena02', 'arena02', P);
  const S = 28;
  // пол
  m.fill(0, 0, 0, S - 1, 0, S - 1, 1);
  m.fill(10, 0, 10, 17, 0, 17, 5); // тёмный центр
  // периметр, высота 6 (чтобы с яруса не выпрыгнуть наружу)
  m.fill(0, 1, 0, S - 1, 6, 0, 2); m.fill(0, 1, S - 1, S - 1, 6, S - 1, 2);
  m.fill(0, 1, 0, 0, 6, S - 1, 2); m.fill(S - 1, 1, 0, S - 1, 6, S - 1, 2);
  // два балкона вдоль стен z=1..5 и z=22..26, плита на y=3 (ходим по y=4)
  m.fill(4, 3, 1, S - 5, 3, 5, 7);
  m.fill(4, 3, S - 6, S - 5, 3, S - 2, 7);
  // ограждение балконов высотой 1 (можно перепрыгнуть/спрыгнуть)
  m.fill(4, 4, 5, S - 5, 4, 5, 2);
  m.fill(4, 4, S - 6, S - 5, 4, S - 6, 2);
  // проёмы в ограждении по центру балкона — спрыгнуть в бой
  m.clear(12, 4, 5, 15, 4, 5);
  m.clear(12, 4, S - 6, 15, 4, S - 6);
  // рампы-лестницы на балконы в углах (ступени 1×1): x=1..3 подъём
  const stairs = (x0, z0, dz) => {
    // 3 ступени: y=1,2,3; ходим по верхушкам
    m.fill(x0, 1, z0, x0 + 1, 1, z0 + 1, 3);
    m.fill(x0, 1, z0 + dz, x0 + 1, 2, z0 + dz + 1, 3);
    m.fill(x0, 1, z0 + dz * 2, x0 + 1, 3, z0 + dz * 2 + 1, 3);
  };
  stairs(1, 8, -1);            // левый передний: подъём к балкону z=1..5
  stairs(S - 3, 8, -1);        // правый передний
  stairs(1, S - 9, 1);         // левый задний
  stairs(S - 3, S - 9, 1);     // правый задний
  // укрытия на нижнем этаже
  const sym = (x0, z0, x1, z1, y0, y1, t) => {
    m.fill(x0, y0, z0, x1, y1, z1, t);
    m.fill(S - 1 - x1, y0, S - 1 - z1, S - 1 - x0, y1, S - 1 - z0, t);
  };
  m.fill(13, 1, 13, 14, 2, 14, 6);       // центральная тумба (дробовик)
  sym(8, 12, 8, 15, 1, 2, 3);            // стенки по бокам центра
  sym(12, 8, 15, 8, 1, 2, 3);            // стенки спереди/сзади центра
  sym(5, 5, 6, 6, 1, 3, 2);              // угловые колонны
  // акцент у спавнов
  m.fill(2, 0, 12, 3, 0, 15, 4); m.fill(S - 4, 0, 12, S - 3, 0, 15, 4);
  m.save(
    [[2.5, 1, 14, 270], [25.5, 1, 14, 90]],
    [
      { type: 1, pos: [14, 3.6, 14] },          // дробовик на тумбе в центре
      { type: 2, pos: [14, 4.6, 3] },           // рейлган на переднем балконе
      { type: 2, pos: [14, 4.6, S - 4] },       // рейлган на заднем балконе
    ],
  );
}
